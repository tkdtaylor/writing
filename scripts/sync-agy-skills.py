#!/usr/bin/env python3
"""Generate Antigravity adapters for this repo's Claude Code roles/commands.

Two kinds of output, both derived from the canonical Claude files
(.claude/agents/<name>.md, .claude/commands/<name>.md):

- Skills, .agents/skills/<name>/SKILL.md: thin pointers to the canonical file. Work in
  the Antigravity IDE, App and CLI. This is how a role runs inline.
- Custom subagents, .agents/agents/<name>.md: one per role, with the canonical body as
  the system prompt and Claude tools/model mapped to Antigravity ones. Only the App and
  CLI support custom subagents (invoke_subagent); the IDE falls back to the skill.

The canonical files are managed by the create-project skill (.claude/skill-manifest.json)
and must not be edited for Antigravity; adapters only add the translation layer
(claude-compat skill).

Idempotent: re-run after create-project adds/renames roles. Outputs whose canonical
file disappeared are reported (not deleted) so the removal is a deliberate act.

Usage: scripts/sync-agy-skills.py [--check]
  --check   exit 1 if any output is missing or stale (no writes)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLAUDE = ROOT / ".claude"
OUT = ROOT / ".agents" / "skills"
AGENTS_OUT = ROOT / ".agents" / "agents"
MARKER = "<!-- generated by scripts/sync-agy-skills.py; do not edit by hand -->"
WRITE_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit"}
# Claude tool -> Antigravity subagent tool names. Verified with agy 2.x: a subagent
# given these names gets exactly these tools. A misspelled name can hang a subagent.
TOOL_MAP = {
    "Read": ["view_file"],
    "Write": ["write_to_file"],
    "Edit": ["replace_file_content"],
    "MultiEdit": ["replace_file_content"],
    "Bash": ["run_command"],
    "Grep": ["grep_search"],
    "Glob": ["grep_search"],
}
MODEL_MAP = {"opus": "pro"}  # everything else inherits the caller's model


def frontmatter(text: str) -> dict[str, str]:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    out: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if line.startswith("#") or ":" not in line or line.startswith(" "):
            continue
        k, v = line.split(":", 1)
        out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def yaml_block(s: str) -> str:
    """Render a description as a YAML folded block (safe for quotes/colons)."""
    words, lines, cur = s.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > 88:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        lines.append(cur)
    return ">-\n" + "\n".join(f"  {ln}" for ln in lines)


def role_adapter(name: str, fm: dict[str, str]) -> str:
    tools = set(re.findall(r'"(\w+)"', fm.get("tools", "")))
    read_only = bool(tools) and not (tools & WRITE_TOOLS)
    mode = (
        "**Read-only role.** While acting as this role, do not create or modify source files; "
        "write only the report the role asks for."
        if read_only
        else "Read-write role (may edit files within the scope the role defines)."
    )
    desc = f"{fm.get('description', name)} (Antigravity adapter for .claude/agents/{name}.md)"
    return f"""---
name: {name}
description: {yaml_block(desc)}
---
{MARKER}

# {name} (Antigravity adapter)

Canonical role definition: [`.claude/agents/{name}.md`](../../../.claude/agents/{name}.md).
It is shared with Claude Code and managed by the create-project skill
(`.claude/skill-manifest.json`), so **do not edit it for Antigravity**.

## How to run this role here

1. Read the [`claude-compat`](../claude-compat/SKILL.md) skill first. It covers
   tool names, `$ARGUMENTS`, sub-agent dispatch, and which hooks run here.
2. Read `.claude/agents/{name}.md` and follow everything below its frontmatter as
   this role's instructions, translating Claude-specific references with
   `claude-compat`.
3. {mode}
4. **Dispatch mode:** when the user or a workflow wants an isolated run and you
   have `invoke_subagent` (Antigravity App and CLI), invoke the `{name}` custom
   subagent (`.agents/agents/{name}.md`) instead of acting inline. Otherwise
   (IDE, or no subagent tool) act as the role inline in this conversation. Say
   which mode you used in your report.
"""


def command_adapter(name: str, fm: dict[str, str]) -> str:
    parallel = "parallel" in name
    extra = (
        "\n5. **Parallel dispatch** needs one isolated sub-agent per task, each in its own "
        "worktree (`scripts/start-task.sh` prints `WORKTREE <path>` under concurrency; the "
        "sub-agent must work only there). Without `invoke_subagent` (IDE), tell the user "
        "and offer to run the same backlog **sequentially inline** instead. Never run "
        "several tasks in one working tree.\n"
        if parallel
        else ""
    )
    hint = fm.get("argument-hint", "")
    desc = (
        f"{fm.get('description', name)}. Invoke as /{name}"
        + (f" {hint}" if hint else "")
        + f" (Antigravity adapter for .claude/commands/{name}.md)"
    )
    return f"""---
name: {name}
description: {yaml_block(desc)}
---
{MARKER}

# /{name} (Antigravity adapter)

Canonical command: [`.claude/commands/{name}.md`](../../../.claude/commands/{name}.md),
which drives [`.claude/backlog-playbook.md`](../../../.claude/backlog-playbook.md).
Both are shared with Claude Code and managed by create-project, so **do not edit
them for Antigravity**.

## How to run this command here

1. Read the [`claude-compat`](../claude-compat/SKILL.md) skill first.
2. Read `.claude/commands/{name}.md`. Wherever it says `$ARGUMENTS`, use whatever
   the user wrote after `/{name}` (empty if nothing). Accepted arguments:
   `{hint or "(none)"}`.
3. Follow `.claude/backlog-playbook.md` with the parameters the command sets.
4. Each "dispatch a `task-executor` / `spec-verifier` / `task-planner` sub-agent"
   step invokes the matching custom subagent (`.agents/agents/<role>.md`) with
   `invoke_subagent` in the App and CLI. In the IDE, use the matching workspace
   skill inline instead. The safety hooks (no-commit-on-main, protect-checkout,
   and others) run through `.agents/hooks.json` in the CLI and App; still follow
   those rules yourself, since the IDE may not run them.{extra}
"""


def subagent(name: str, text: str) -> str:
    """Custom subagent: canonical body as system prompt, tools/model mapped."""
    fm = frontmatter(text)
    body = re.sub(r"^---\n.*?\n---\n", "", text, count=1, flags=re.S).lstrip("\n")
    claude_tools = re.findall(r'"(\w+)"', fm.get("tools", ""))
    tools: list[str] = []
    for t in claude_tools:
        for mapped in TOOL_MAP.get(t, []):
            if mapped not in tools:
                tools.append(mapped)
    tools_yaml = "".join(f"\n  - {t}" for t in tools)
    model = MODEL_MAP.get(fm.get("model", ""), "inherit")
    desc = f"{fm.get('description', name)} (Antigravity subagent for .claude/agents/{name}.md)"
    return f"""---
name: {name}
description: {yaml_block(desc)}
mainAgent: false
subagent: true
model: {model}
tools:{tools_yaml}
---
{MARKER}

# Antigravity notes

This prompt is generated from `.claude/agents/{name}.md`, written for Claude Code.
Before starting, read `.agents/skills/claude-compat/SKILL.md` to translate
Claude tool names (Read, Write, Edit, Bash, Grep, Glob), `CLAUDE.md` references
(read `AGENTS.md`), and hook behavior. Your tools: {", ".join(tools) or "(none)"}.

# Role

{body}"""


def sync(wanted: dict[Path, str], check: bool) -> list[str]:
    stale = []
    for target, content in wanted.items():
        if not target.exists() or target.read_text() != content:
            stale.append(target.relative_to(ROOT).as_posix())
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
    return stale


def generated(path: Path) -> bool:
    return path.exists() and "generated by scripts/sync-agy-skills.py" in path.read_text()


def main() -> int:
    check = "--check" in sys.argv
    wanted: dict[Path, str] = {}
    for f in sorted((CLAUDE / "agents").glob("*.md")):
        text = f.read_text()
        wanted[OUT / f.stem / "SKILL.md"] = role_adapter(f.stem, frontmatter(text))
        wanted[AGENTS_OUT / f"{f.stem}.md"] = subagent(f.stem, text)
    for f in sorted((CLAUDE / "commands").glob("*.md")):
        wanted[OUT / f.stem / "SKILL.md"] = command_adapter(f.stem, frontmatter(f.read_text()))

    stale = sync(wanted, check)

    existing = list(OUT.glob("*/SKILL.md")) + list(AGENTS_OUT.glob("*.md"))
    orphans = [
        p.relative_to(ROOT).as_posix() for p in existing if generated(p) and p not in wanted
    ]

    verb = "stale/missing" if check else "written"
    print(f"{len(wanted)} outputs; {len(stale)} {verb}: {', '.join(stale) or '-'}")
    if orphans:
        print(f"orphaned outputs (canonical file removed): {', '.join(orphans)}")
    return 1 if check and (stale or orphans) else 0


if __name__ == "__main__":
    sys.exit(main())
